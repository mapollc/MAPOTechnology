    fcstHour() {
        var h = config.curTime.getUTCHours(),
            m = config.curTime.getUTCMonth() + 1,
            m = (m < 10 ? '0' : '') + m,
            d = config.curTime.getUTCDate(),
            d = (d < 10 ? '0' : '') + d,
            t;

        if (h >= 19 && h <= 23 || h == 0) {
            t = '18';
        } else if (h >= 1 && h <= 6) {
            t = '00';
        } else if (h >= 7 && h <= 12) {
            t = '06';
        } else {
            t = '12';
        }

        return `${config.curTime.getUTCFullYear()}-${m}-${d}T${t}:00:00.000Z`;
    }

